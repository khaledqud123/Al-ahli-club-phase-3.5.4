/* =========================================================
   POINTER / TILT EFFECT
========================================================= */

function initPointerEffects(){

  if(
    window.matchMedia(
      "(pointer: coarse)"
    ).matches
  ){
    return;
  }


  const cards =
    document.querySelectorAll(
      ".experience-card, .admin-card, .membership-card"
    );


  cards.forEach(card => {

    card.addEventListener(
      "mousemove",
      event => {

        const rect =
          card.getBoundingClientRect();


        const x =
          event.clientX -
          rect.left;

        const y =
          event.clientY -
          rect.top;


        const rotateY =
          ((x / rect.width) - .5) * 4;

        const rotateX =
          ((y / rect.height) - .5) * -4;


        card.style.transform =
          `perspective(800px)
           rotateX(${rotateX}deg)
           rotateY(${rotateY}deg)
           translateY(-5px)`;

      }
    );


    card.addEventListener(
      "mouseleave",
      () => {

        card.style.transform =
          "";

      }
    );

  });

}


