function initScrollEffects(){

  const sections =
    document.querySelectorAll(
      "main section[id]"
    );

  const navLinks =
    document.querySelectorAll(
      ".nav-links a"
    );


  const observer =
    new IntersectionObserver(
      entries => {

        entries.forEach(entry => {

          if(!entry.isIntersecting){
            return;
          }


          const id =
            entry.target.id;


          navLinks.forEach(link => {

            link.classList.toggle(
              "active",
              link.getAttribute("href") ===
              `#${id}`
            );

          });


          document
            .querySelectorAll(".rail-dot")
            .forEach(dot => {

              dot.classList.toggle(
                "active",
                dot.dataset.target ===
                `#${id}`
              );

            });

        });

      },
      {
        threshold:.2,
        rootMargin:"-20% 0px -55% 0px"
      }
    );


  sections.forEach(
    section =>
      observer.observe(section)
  );

}


/* =========================================================
   COUNTERS
========================================================= */

function initCounters(){

  const counters =
    document.querySelectorAll(
      "[data-counter]"
    );

  if(!counters.length) return;


  const observer =
    new IntersectionObserver(
      entries => {

        entries.forEach(entry => {

          if(!entry.isIntersecting){
            return;
          }


          const element =
            entry.target;

          if(element.dataset.counted){
            return;
          }

          element.dataset.counted =
            "true";


          const target =
            Number(
              element.dataset.counter
            );

          animateCounter(
            element,
            target
          );

          observer.unobserve(element);

        });

      },
      {
        threshold:.6
      }
    );


  counters.forEach(counter =>
    observer.observe(counter)
  );

}


function animateCounter(
  element,
  target
){

  const duration =
    target > 1000
      ? 1600
      : 1100;

  const start =
    performance.now();


  function update(now){

    const progress =
      Math.min(
        (now - start) / duration,
        1
      );


    const eased =
      1 -
      Math.pow(
        1 - progress,
        3
      );


    const value =
      Math.floor(
        target * eased
      );


    element.textContent =
      value.toLocaleString(
        currentLanguage === "ar"
          ? "ar-EG"
          : "en-US"
      );


    if(progress < 1){

      requestAnimationFrame(
        update
      );

    }else{

      element.textContent =
        target.toLocaleString(
          currentLanguage === "ar"
            ? "ar-EG"
            : "en-US"
        );

    }

  }


  requestAnimationFrame(update);

}


